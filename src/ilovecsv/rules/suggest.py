"""Generate a starter rule file from a workbook profile.

The output is a *draft*: it encodes what the data currently looks like (types,
observed ranges, small category sets, columns that are never empty) so the user
can tighten or loosen it instead of starting from a blank file.
"""

from __future__ import annotations

import math
from collections import Counter
from typing import Any

import yaml

from ..profiling import SheetProfile, collapse_ws

_TYPE_MAP = {"int": "int", "float": "float", "date": "date", "bool": "bool", "text": "text", "category": "text"}


def suggest_rules(profiles: dict[str, SheetProfile]) -> str:
    sheets = [_sheet_rules(p) for p in profiles.values()]
    doc: dict[str, Any] = {"version": 1}
    if len(sheets) == 1:
        doc.update(sheets[0])
    else:
        doc["sheets"] = sheets
    header = (
        "# Draft rules generated by IloveCSV from the current data.\n"
        "# Observed ranges and category lists describe the file as it is today:\n"
        "# review them, tighten what you know, and add cross-column rules under `rules:`.\n"
    )
    body = yaml.safe_dump(doc, sort_keys=False, allow_unicode=True, default_flow_style=None, width=100)
    return header + body + _rules_example()


def _sheet_rules(p: SheetProfile) -> dict[str, Any]:
    columns: dict[str, Any] = {}
    key: list[str] | None = None
    for name, c in p.columns.items():
        if c.inferred_type == "empty":
            continue
        r: dict[str, Any] = {}
        if c.missing_rate == 0:
            r["required"] = True
        if c.inferred_type in _TYPE_MAP and c.type_share >= 0.9:
            r["type"] = _TYPE_MAP[c.inferred_type]
        if c.inferred_type in ("int", "float") and c.numeric and not c.is_identifier:
            lo, hi = c.numeric["min"], c.numeric["max"]
            r["min"] = 0 if lo >= 0 else _round_down(lo)
            r["max"] = _round_up(hi)
        if c.inferred_type == "category":
            r["allowed"] = _canonical_values(c.top_values, c.case_variants)
        if c.is_identifier and c.inferred_type == "text" and c.lengths and c.lengths["mode_share"] >= 0.99:
            r["min_length"] = r["max_length"] = c.lengths["mode"]
        non_null = c.n_rows - c.n_missing
        if c.is_identifier and non_null and c.n_distinct == non_null:
            r["unique"] = True
            if key is None:
                key = [name]
        columns[name] = r
    out: dict[str, Any] = {"sheet": p.name}
    if key:
        out["key"] = key
        columns[key[0]].pop("unique", None)  # the key check already covers uniqueness
    out["columns"] = columns
    return out


def _canonical_values(top: list[dict[str, Any]], variants: list[dict[str, Any]]) -> list[str]:
    counts: Counter = Counter()
    canon = {collapse_ws(v["value"]).casefold(): g["canonical"] for g in variants for v in g["variants"]}
    for t in top:
        s = str(t["value"])
        counts[canon.get(collapse_ws(s).casefold(), collapse_ws(s))] += t["count"]
    return [v for v, _ in counts.most_common()]


def _round_up(x: float) -> float:
    if x == 0:
        return 0
    mag = 10 ** max(0, math.floor(math.log10(abs(x))) - 1)
    v = math.ceil(x / mag) * mag
    return int(v) if float(v).is_integer() else v


def _round_down(x: float) -> float:
    return -_round_up(-x)


def _rules_example() -> str:
    return (
        "# Example cross-column rules (uncomment and adapt):\n"
        "# rules:\n"
        "#   - id: end_after_start\n"
        "#     when: \"end_date is not null\"\n"
        "#     check: \"end_date >= start_date\"\n"
        "#   - id: total_matches\n"
        "#     check: \"abs(total - quantity * unit_price) <= 0.01\"\n"
        "#     fix: {column: total, to: \"quantity * unit_price\"}\n"
    )

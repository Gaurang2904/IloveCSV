"""Generate a starter rule file from a workbook profile.

The output is a *draft* for a person to review. It must not simply describe the
data as it is, or the draft would make the data's own errors legal. So:

* numeric bounds come from the *bulk* of the values (robust z <= 3.5), widened by
  the bulk's own width, instead of the observed min/max that outliers define;
* a column is required when at most 20% of it is empty: a few gaps in an
  otherwise complete column are more likely errors than an optional field;
* email and phone columns get format checks instead of text or numeric ranges;
* documentation sheets (Readme, Notes, ...) are skipped.
"""

from __future__ import annotations

import math
from collections import Counter
from typing import Any

import yaml

from ..profiling import SheetProfile, collapse_ws

_TYPE_MAP = {"int": "int", "float": "float", "date": "date", "bool": "bool", "text": "text", "category": "text"}


REQUIRED_MAX_MISSING = 0.2
_DOC_SHEET_NAMES = {"readme", "read me", "notes", "about", "instructions", "info", "documentation", "help"}


def is_documentation_sheet(p: SheetProfile) -> bool:
    if p.name.strip().lower() in _DOC_SHEET_NAMES:
        return True
    cols = list(p.columns.values())
    return (0 < len(cols) <= 2 and all(c.inferred_type in ("text", "empty") for c in cols)
            and any(c.lengths and c.lengths["mean"] >= 40 for c in cols))


def suggest_rules(profiles: dict[str, SheetProfile], for_ml: bool = False) -> str:
    """Draft rules. for_ml=True (one-click prepare) only requires id columns: in a training table
    missing feature values are normal and are handled by imputation in the ML pipeline, so they
    are reported as missingness per column, not as errors."""
    data_sheets = [p for p in profiles.values() if not is_documentation_sheet(p)] or list(profiles.values())
    skipped = [p.name for p in profiles.values() if p not in data_sheets]
    sheets = [_sheet_rules(p, for_ml) for p in data_sheets]
    doc: dict[str, Any] = {"version": 1}
    if len(sheets) == 1:
        doc.update(sheets[0])
    else:
        doc["sheets"] = sheets
    header = (
        "# Draft rules generated by IloveCSV from the current data.\n"
        "# Observed ranges and category lists describe the file as it is today:\n"
        "# review them, tighten what you know, and add cross-column rules under `rules:`.\n"
        "# Numeric bounds come from the bulk of the values, so outliers are not made legal.\n"
    )
    if skipped:
        header += f"# Skipped documentation sheet(s): {', '.join(skipped)}\n"
    body = yaml.safe_dump(doc, sort_keys=False, allow_unicode=True, default_flow_style=None, width=100)
    return header + body + _rules_example()


def with_prepare_options(rules_text: str, sheet_columns: dict[str, list[str]], target: str | None = None,
                         remove_exact_duplicates: bool | None = None,
                         target_labels: list[str] | None = None, source: Any = None) -> str:
    """Set the target and the exact-duplicate policy in a rule file (suggested or saved).

    `sheet_columns` maps sheet name -> column names; the target goes to the first validated sheet
    that has that column. Raises ValueError if no sheet has it.
    """
    doc = yaml.safe_load(rules_text) or {}
    single = "sheets" not in doc
    blocks = [doc] if single else doc["sheets"]
    first_sheet = next(iter(sheet_columns), None)
    if not target and target_labels:  # labels for the target a saved config already declares
        target = next((b["target"] for b in blocks if b.get("target")), None)
    if target:
        block = next((b for b in blocks if target in sheet_columns.get(b.get("sheet") or first_sheet, [])), None)
        if block is None:
            raise ValueError(f"target column '{target}' was not found in the validated sheets")
        block["target"] = target
        rule = (block.get("columns") or {}).get(target)
        if isinstance(rule, dict):
            rule.pop("required", None)  # a missing label is reported as target.missing instead
            if target_labels is None and rule.get("allowed"):
                target_labels = list(rule["allowed"])  # the labels the data uses, placeholders excluded
        if target_labels:
            block["target_labels"] = [str(x).strip() for x in target_labels if str(x).strip()]
    elif target_labels:
        raise ValueError("target labels need a target column")
    if remove_exact_duplicates is not None:
        for b in blocks:
            b["duplicates"] = {"exact": "remove" if remove_exact_duplicates else "review"}
    if source is not None:
        chosen = source.model_dump(exclude_defaults=True)
        if chosen:
            doc["source"] = chosen
        else:
            doc.pop("source", None)
    return RECIPE_HEADER + yaml.safe_dump(doc, sort_keys=False, allow_unicode=True, default_flow_style=None,
                                          width=100)


RECIPE_HEADER = (
    "# IloveCSV recipe (prepare config): how the source becomes tables, the rules, the cleaning policy and\n"
    "# the review decisions. Re-use it with `ilovecsv prepare --config` to prepare new batches (e.g. later\n"
    "# scoring data) exactly the same way; the report says which recorded decisions still applied.\n"
)


def _sheet_rules(p: SheetProfile, for_ml: bool = False) -> dict[str, Any]:
    columns: dict[str, Any] = {}
    key: list[str] | None = None
    for name, c in p.columns.items():
        if c.inferred_type == "empty":
            continue
        r: dict[str, Any] = {}
        if c.missing_rate <= REQUIRED_MAX_MISSING and (c.is_identifier or not for_ml):
            r["required"] = True
        if c.semantic == "email":
            r["format"] = "email"
            columns[name] = r
            continue
        if c.semantic == "phone":
            r["format"] = "phone"
            r["phone_digits"] = c.phone_digits or 10
            columns[name] = r
            continue
        if c.inferred_type in _TYPE_MAP and c.type_share >= 0.9:
            r["type"] = _TYPE_MAP[c.inferred_type]
        if c.inferred_type in ("int", "float") and c.numeric and not c.is_identifier:
            num = c.numeric
            lo, hi = num["bulk_min"], num["bulk_max"]
            width = (hi - lo) or abs(hi) or 1.0
            # A suggested bound is a claim that values beyond it are errors. Keep it only if the data
            # itself barely violates it: a "valid range" broken by 6% of the measurements is a summary
            # of the distribution (heavy tails, signed signals), not a validity rule.
            allowed = max(2, int(0.005 * num.get("count", 0)))
            # (Almost) never negative -> min 0: in a small file a stray -4 can sit inside the robust
            # bulk, and an age, count or price below zero is an error, not part of the range.
            if num["median"] >= 0 and num.get("negative_share", 0) <= 0.05 and num.get("n_negative", 0) <= allowed:
                r["min"] = 0
            elif num.get("n_below_window", 0) <= allowed:
                r["min"] = _round_down(lo - width)
            if num.get("n_above_window", 0) <= allowed:
                r["max"] = _round_up(hi + width)
        if c.inferred_type == "category":
            r["allowed"] = _canonical_values(c.categories or c.top_values, c.case_variants)
        if c.is_identifier and c.inferred_type == "text" and c.lengths and c.lengths["mode_share"] >= 0.99:
            r["min_length"] = r["max_length"] = c.lengths["mode"]
        non_null = c.n_rows - c.n_missing
        if c.is_identifier and non_null and c.n_distinct == non_null:
            r["unique"] = True
            if key is None:
                key = [name]
        columns[name] = r
    out: dict[str, Any] = {"sheet": p.name}
    if key:
        out["key"] = key
        columns[key[0]].pop("unique", None)  # the key check already covers uniqueness
    out["columns"] = columns
    return out


def _canonical_values(top: list[dict[str, Any]], variants: list[dict[str, Any]]) -> list[str]:
    counts: Counter = Counter()
    canon = {collapse_ws(v["value"]).casefold(): g["canonical"] for g in variants for v in g["variants"]}
    for t in top:
        s = str(t["value"])
        counts[canon.get(collapse_ws(s).casefold(), collapse_ws(s))] += t["count"]
    return [v for v, _ in counts.most_common()]


def _round_up(x: float) -> float:
    if x == 0:
        return 0
    mag = 10 ** max(0, math.floor(math.log10(abs(x))) - 1)
    v = math.ceil(x / mag) * mag
    return int(v) if float(v).is_integer() else v


def _round_down(x: float) -> float:
    return -_round_up(-x)


def _rules_example() -> str:
    return (
        "# Example cross-column rules (uncomment and adapt):\n"
        "# rules:\n"
        "#   - id: end_after_start\n"
        "#     when: \"end_date is not null\"\n"
        "#     check: \"end_date >= start_date\"\n"
        "#   - id: total_matches\n"
        "#     check: \"abs(total - quantity * unit_price) <= 0.01\"\n"
        "#     fix: {column: total, to: \"quantity * unit_price\"}\n"
    )
